"""Puertos (interfaces) que la capa de aplicación necesita. Inversión de dependencias (SOLID-D)."""
from __future__ import annotations

from typing import Protocol

from src.domain.entidades import Alumno, Programa, Solicitud
from src.domain.eventos import EventoDominio


class AlumnoRepository(Protocol):
    def obtener(self, alumno_id: str) -> Alumno | None: ...
    def agregar(self, alumno: Alumno) -> None: ...


class ProgramaRepository(Protocol):
    def obtener(self, programa_id: str) -> Programa | None: ...
    def listar(self, solo_habilitados: bool = False) -> list[Programa]: ...
    def guardar(self, programa: Programa) -> None: ...


class SolicitudRepository(Protocol):
    def obtener(self, solicitud_id: str) -> Solicitud | None: ...
    def agregar(self, solicitud: Solicitud) -> None: ...
    def guardar(self, solicitud: Solicitud) -> None: ...
    def listar(self, alumno_id: str | None = None, estado: str | None = None) -> list[Solicitud]: ...
    def siguiente_id(self) -> str: ...


class Publicador(Protocol):
    def publicar(self, eventos: list[EventoDominio]) -> None: ...
    def listar(self, solicitud_id: str) -> list[EventoDominio]: ...


class UnidadDeTrabajo(Protocol):
    """Confirma o revierte la transacción (ADR-006/ADR-007)."""

    def commit(self) -> None: ...
    def rollback(self) -> None: ...
